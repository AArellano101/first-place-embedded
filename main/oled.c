esp_err_t oled_init(i2c_master_bus_handle_t bus, uint8_t address, unsigned height)
{
    if (!bus || (height != 32 && height != 64) || address > 0x7f) {
        return ESP_ERR_INVALID_ARG;
    }
    if (panel) return ESP_ERR_INVALID_STATE;
    esp_lcd_panel_io_handle_t io = NULL;
    const esp_lcd_panel_io_i2c_config_t io_config = {
        .dev_addr = address,
        .scl_speed_hz = OLED_I2C_HZ,
        .control_phase_bytes = 1,
        .dc_bit_offset = 6,
        .lcd_cmd_bits = 8,
        .lcd_param_bits = 8,
    };
    esp_err_t err = esp_lcd_new_panel_io_i2c(bus, &io_config, &io);
    if (err != ESP_OK) return err;
    esp_lcd_panel_ssd1306_config_t vendor = {.height = height};
    const esp_lcd_panel_dev_config_t config = {
        .reset_gpio_num = -1,
        .bits_per_pixel = 1,
        .vendor_config = &vendor,
    };
    err = esp_lcd_new_panel_ssd1306(io, &config, &panel);
    if (err != ESP_OK) goto fail;
    display_height = height;
    if ((err = esp_lcd_panel_reset(panel)) != ESP_OK) goto fail;
    if ((err = esp_lcd_panel_init(panel)) != ESP_OK) goto fail;
    if ((err = esp_lcd_panel_mirror(panel, OLED_MIRROR_X, OLED_MIRROR_Y)) != ESP_OK) goto fail;
    oled_clear();
    if ((err = oled_show()) != ESP_OK) goto fail;
    if ((err = esp_lcd_panel_disp_on_off(panel, true)) != ESP_OK) goto fail;
    return ESP_OK;
fail:
    if (panel) esp_lcd_panel_del(panel);
    panel = NULL;
    display_height = 0;
    esp_lcd_panel_io_del(io);
    return err;
}

void oled_clear(void)
{
    memset(pixels, 0, sizeof(pixels));
}

void oled_write_text(unsigned column, unsigned row, const char *text)
{
    if (!text || column >= WIDTH / CELL_WIDTH) return;
    while (*text && row < display_height / 8) {
        unsigned char c = (unsigned char)*text++;
        if (c == '\n') {
            column = 0;
            row++;
            continue;
        }
        if (column >= WIDTH / CELL_WIDTH) {
            column = 0;
            if (++row >= display_height / 8) break;
        }
        if (c < 32 || c > 126) c = '?';
        uint8_t *cell = &pixels[row * WIDTH + column * CELL_WIDTH];
        memcpy(cell, font[c - 32], 5);
        cell[5] = 0;
        column++;
    }
}

esp_err_t oled_show(void)
{
    if (!panel) return ESP_ERR_INVALID_STATE;
    return esp_lcd_panel_draw_bitmap(panel, 0, 0, WIDTH, display_height, pixels);
}
